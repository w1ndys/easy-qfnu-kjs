-- 0005 默认 cron 改成 5 字段：0001 的种子行写的是 6 段 `0 10 4 * * 6`（多一个秒
-- 字段），而 cronexpr 只认 5 字段（分 时 日 月 周）。库里这条旧值会让启动流程判它
-- 非法并回落到代码默认值，管理员在设置页看到的 cron_expr 与实际调度对不上。
--
-- 只改数据，不动 0001：0001–0004 已应用，一个字节都不改。
-- 幂等靠 WHERE 钉住旧值：重复执行时不再命中，`updated_at` 也不会被刷新；
-- 管理员改成别的表达式后重跑同样碰不到这一行。
UPDATE settings
   SET value = '10 4 * * 6',
       updated_at = now()
 WHERE key = 'cron_expr'
   AND value = '0 10 4 * * 6';
